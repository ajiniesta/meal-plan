const ing = (value: string): Ingredient => {
  const [name, section = "despensa"] = value.split("|");
  return { name, section: section as IngredientSection };
};

interface RecipeOptions {
  fishKind?: Recipe["fishKind"];
  mealSlots?: MealType[];
  emoji?: string;
}

